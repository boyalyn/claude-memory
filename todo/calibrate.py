#!/usr/bin/env python3
"""Summarise TIME-LOG.md (actual vs estimate per category) into memory/user-time-estimates.md.

Run after every new TIME-LOG row. Prints the summary; --category=X prints that category's line only.
"""
import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "memory" / "user-time-estimates.md"
MIN_N = 3  # rows needed before a category's multiplier is used for estimates


def hours(s):
    m = re.fullmatch(r"(\d+(?:\.\d+)?)(m|h|d)", s.strip())
    if not m:
        return None
    n, u = float(m.group(1)), m.group(2)
    return n / 60 if u == "m" else n if u == "h" else n * 8


def rows():
    for line in (HERE / "TIME-LOG.md").read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 7 or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", cells[0]):
            continue
        est, act = hours(cells[4]), hours(cells[5])
        if est and act:
            yield {"done": cells[0], "task": cells[2], "cat": cells[3], "est": est, "act": act}


def summary():
    by = defaultdict(list)
    for r in rows():
        by[r["cat"]].append(r)
    out = []
    for cat in sorted(by, key=lambda c: -len(by[c])):
        rs = by[cat]
        ratios = [r["act"] / r["est"] for r in rs]
        med = statistics.median(ratios)
        line = f"- {cat}: n={len(rs)}, median actual/est = {med:.2f}, range {min(ratios):.2f}–{max(ratios):.2f}, last {rs[-1]['done']}"
        line += f" → multiply raw estimates by {med:.2f}" if len(rs) >= MIN_N else f" → fewer than {MIN_N} samples, do not adjust yet"
        out.append((cat, line))
    return out, sum(len(v) for v in by.values())


def main():
    lines, total = summary()
    only = next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--category=")), None)
    if only:
        print(next((l for c, l in lines if c == only), f"- {only}: no samples yet"))
        return
    body = "\n".join(l for _, l in lines) or "- no finished items with actual time yet"
    OUT.write_text(f"""---
name: user-time-estimates
description: "How long the user's tasks really take vs Claude's estimates, per category (measured from todo/TIME-LOG.md); use when estimating est: for /todo"
metadata:
  type: user
---

Generated by ~/claude-memory/todo/calibrate.py from {total} logged item(s) in todo/TIME-LOG.md — do not edit by hand; rerun the script.
Measured facts only: ratio = actual time the user reported / Claude's estimate. Categories with n<{MIN_N} are not used for adjustment.
When estimating a new item: make the raw estimate, then multiply by the category's median if n≥{MIN_N}, and say in the reply that it was adjusted. See [[project-todo]].

{body}
""", encoding="utf-8")
    print(body)


if __name__ == "__main__":
    main()
